// Writes docs/internal/cinder-models.md from measurement. g++ -O2 -std=c++17 -I../Source cinder_models_doc.cpp -o /tmp/cmd && /tmp/cmd > ../docs/internal/cinder-models.md
#include "SqCinderDsp.h"
#include <cstdio>
#include <cctype>
#include <string>
using namespace Eng;
int main()
{
    std::printf ("# Cinder: the ten models, measured\n\nGenerated by `tests/cinder_models_doc.cpp` from the shipping DSP (`Source/SqCinderDsp.h`). INTERNAL.\n\n"
                 "Each row is a 1 kHz sine at **-18 dBFS (\"0 VU\")** through the model at 4x oversampling, Bias 0, Dynamics 30 %%, Auto gain off. "
                 "Harmonics are in dB below the fundamental. The plug-in's live readout measures the same thing for the current settings.\n\n");
    for (int m = 0; m < Cinder::numModels; ++m)
    {
        const auto& d = Cinder::model (m);
        { std::string a (d.archetype); a[0] = (char) std::toupper ((unsigned char) a[0]); std::printf ("## %d. %s\n\n%s.\n\n", m + 1, d.name, a.c_str()); }
        std::printf ("- **Chain:** input high-pass %.0f Hz (Q %.2f)", d.inHpHz, d.inHpQ);
        if (d.emLowDb != 0 || d.emMidDb != 0 || d.emHighDb != 0) std::printf (", drive EQ%s%s%s", d.emLowDb != 0 ? " low" : "", d.emMidDb != 0 ? " mid" : "", d.emHighDb != 0 ? " high" : "");
        std::printf (", stage %s%s%s, output colour, bandwidth %.0f Hz.\n", Nonlinear::modelName (d.nlA), d.nlB >= 0 ? " into " : "", d.nlB >= 0 ? Nonlinear::modelName (d.nlB) : "", d.bandwidthHz);
        if (d.limiter) std::printf ("- **Limiter:** fast program-dependent limiting ahead of the stage (release 60 ms to 1.2 s).\n");
        if (d.slewFsPerMs > 0) std::printf ("- **Slew:** soft slew limit, %.0f full-scale per ms.\n", d.slewFsPerMs);
        std::printf ("\n| Drive | H2 | H3 | H4 | H5 | H6 | H7 | THD %% |\n|---:|---:|---:|---:|---:|---:|---:|---:|\n");
        for (float drv : { 0.0f, 6.0f, 12.0f, 18.0f, 24.0f, 36.0f })
        {
            Cinder::Processor c; c.p.modelA = m; c.p.driveDb = drv; c.p.autoGain = false; c.prepare (48000, 480);
            float h[10]; const double thd = c.harmonics (-18.0f, h);
            std::printf ("| %+.0f dB | %.1f | %.1f | %.1f | %.1f | %.1f | %.1f | %.2f |\n", drv, h[1], h[2], h[3], h[4], h[5], h[6], thd);
        }
        std::printf ("\n");
    }
}
