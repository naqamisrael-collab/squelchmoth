RECYCLE = {'Spaces | Echo Recycle Wash': (35, 375), 'Sound Design | Recycled Glitch': (45, 250)}

def main():
    cat = json.load(open(sys.argv[1]))
    pres = {e['name']: e['presets'] for e in cat}
    problems = []
    for c in CH:
        for i, (pl, q) in enumerate(c['slots']):
            if pl not in pres: problems.append('%s: no plug-in %s' % (c['name'], pl)); continue
            ps = pres[pl]
            hit = [p for p in ps if p.lower() == q.lower()] or [p for p in ps if p.lower().endswith('| ' + q.lower())] or [p for p in ps if q.lower() in p.lower()]
            if not hit: problems.append('%s: %s has no preset like "%s"' % (c['name'], pl, q)); continue
            c['slots'][i] = (pl, hit[0])
        assert len(c['slots']) <= 8
        if c['routing'] == LANES: assert len(c['slots']) >= 2
    names = [c['name'] for c in CH]
    dup = set(n for n in names if names.count(n) > 1)
    if dup: problems.append('duplicate chain names %s' % dup)
    if problems:
        print('\n'.join(problems)); sys.exit(1)
    cats = {}
    for c in CH: cats[c['category']] = cats.get(c['category'], 0) + 1
    print(len(CH), 'chains:', cats)
    assert len(CH) == 200, len(CH)
    # two-lane chains: first half of the slots in lane A (slots 1-4), the rest in lane B (slots 5-8)
    for c in CH:
        if c['routing'] == LANES:
            s = c['slots']; h = (len(s) + 1) // 2
            a, b = s[:h], s[h:]
            c['slots'] = a + [('', '')] * (4 - len(a)) + b
    def esc(x): return json.dumps(x)
    out = os.path.join(ROOT, 'Source', 'SqHiveChains.h')
    with open(out, 'w') as f:
        f.write('#pragma once\n// Hive Rack factory chains (generated by scripts/gen_hive_chains.py from the real catalogue; do not edit by hand).\n')
        f.write('// Every slot is a Signature effect and one of its presets. Two-lane chains put lane A in slots 1-4 and lane B in 5-8.\n#include <vector>\n\n')
        f.write('namespace HiveChains\n{\n    struct Slot { const char* plugin; const char* preset; };\n')
        f.write('    struct Chain { const char* name; const char* category; int routing; std::vector<Slot> slots; float recycle = 0.0f, recycleMs = 250.0f; };\n')
        f.write('    inline const std::vector<Chain>& chains()\n    {\n        static const std::vector<Chain> c {\n')
        for c in CH:
            rc, rt = RECYCLE.get(c['name'], (0, 250))
            sl = ', '.join('{ %s, %s }' % (esc(p), esc(q)) for p, q in c['slots'])
            f.write('            { %s, %s, %d, { %s }, %.1ff, %.1ff },\n' % (esc(c['name']), esc(c['category']), c['routing'], sl, rc, rt))
        f.write('        };\n        return c;\n    }\n}\n')
    json.dump([dict(name=c['name'], category=c['category'], routing=c['routing'], slots=c['slots'], recycle=RECYCLE.get(c['name'], (0, 250))[0],
                    recycleMs=RECYCLE.get(c['name'], (0, 250))[1]) for c in CH],
              open(os.path.join(ROOT, 'scripts', 'hive_chains.json'), 'w'), indent=1)
    print('wrote', out)

if __name__ == '__main__':
    main()
