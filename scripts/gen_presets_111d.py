PLUGS = {}   # name -> (param ids in bank order, prop ids, list of presets)
def plug(name, params, props):
    PLUGS[name] = (params, props, [])
def add(name, preset, vals, props):
    params, propids, lst = PLUGS[name]
    for k in vals: assert k in params, (name, k)
    for k in props: assert k in propids, (name, k)
    lst.append(dict(name=preset, vals=vals, props=props))

